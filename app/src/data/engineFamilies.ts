export interface EngineTransmissionMatch {
  transId: string; // Must match a key in TRANSMISSIONS_DB (src/data/engineData.ts)
  fitment: 'direct' | 'variant_bellhousing' | 'adapter';
  notes: string;
}

export interface EngineFamilySpec {
  id: string;
  brand: EngineBrand;
  make: string;
  family: string;
  code: string;
  name: string;
  shortName: string;
  configuration: EngineConfigurationType;
  cylinders: number;
  yearStart: number;
  yearEnd: number;
  bore: number;            // inches
  stroke: number;          // inches
  displacementCi: number;  // factory advertised / calculated CID
  displacementL: number;   // liters
  rodLength: number;       // inches
  deckHeight: number;      // inches
  deckClearance: number;   // inches (negative = piston proud of deck)
  gasketThickness: number; // inches
  chamberCc: number;       // cc
  pistonReliefCc: number;  // cc (positive = dish/relief, negative = dome)
  factoryCR: string;       // published factory compression ratio range
  blockMaterial: string;
  headType: string;
  firingOrder: string;
  bellhousingPattern: string;
  bellhousingNotes: string;
  recommendedTransId: string; // Must match TRANSMISSIONS_DB
  compatibleTransmissions: EngineTransmissionMatch[];
  camBaseline: EngineCamBaseline;
  inductionBaseline: {
    selectedIntake: string;
    inductionDress: InductionDressMode;
    carbCfm: number;
    targetAFR: number;
    ignitionTiming: number;
    sparkPlugGap: number;
    fuelSystemLabel: string;
  };
  pistonAlloyBaseline: PistonAlloy;
  ringApplicationBaseline: RingApplication;
  fuelType?: EngineFuelType;
  aspiration?: EngineAspirationType;
  estimatedFields: string[];
  shopNotes: string;
}

